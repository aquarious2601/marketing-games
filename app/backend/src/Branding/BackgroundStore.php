<?php

declare(strict_types=1);

namespace App\Branding;

use Symfony\Component\DependencyInjection\Attribute\Autowire;
use Symfony\Component\HttpFoundation\File\UploadedFile;

/**
 * The picture behind a game (F35 R6–R15).
 *
 * A sibling of {@see LogoStore} rather than a generalisation of it. The two
 * accept different files for different reasons: a logo is a drawing, so SVG
 * belongs there and the sanitiser with it; a background is a photograph,
 * where a document would be upload surface with nothing to gain (F35 §5).
 * One class serving both would need a flag to say which set of rules
 * applies, and a flag like that is where the wrong rule eventually gets
 * applied.
 *
 * What the two do share is the discipline: nothing about an upload is
 * believed. Not its name, not its extension, not the content type the
 * browser declared. The file is opened and looked at, and the name it is
 * stored under is generated here.
 */
final class BackgroundStore
{
    /** F35 R8. A player waits for this over a shop's wifi. */
    public const MAX_BYTES = 5 * 1024 * 1024;

    /** F35 R9. Below this it is a thumbnail stretched across a phone. */
    public const MIN_LONGEST_SIDE = 1200;

    /** F35 R10. Where a decoder's memory stops being somebody else's problem. */
    public const MAX_SIDE = 8000;

    /**
     * Raster only, verified by reading the file.
     *
     * @var array<int, string> image type constant => content type served back
     */
    private const ACCEPTED = [
        \IMAGETYPE_PNG => 'image/png',
        \IMAGETYPE_JPEG => 'image/jpeg',
        \IMAGETYPE_WEBP => 'image/webp',
    ];

    public function __construct(
        #[Autowire('%kernel.project_dir%/var/uploads/backgrounds')]
        private readonly string $directory,
    ) {
    }

    /**
     * @return array{filename: string, contentType: string}
     *
     * @throws UploadRejected
     */
    public function store(UploadedFile $file): array
    {
        if (!$file->isValid()) {
            throw new UploadRejected('background.upload_failed', [], 'The upload did not complete.');
        }

        $size = (int) $file->getSize();

        if ($size > self::MAX_BYTES) {
            throw new UploadRejected(
                'background.too_large',
                [
                    '%max%' => (int) (self::MAX_BYTES / 1024 / 1024),
                    // F35 R23: the size it actually was, so the shop knows
                    // whether they need a different export or a different
                    // picture.
                    '%size%' => $this->megabytes($size),
                ],
                'The background is too large.',
            );
        }

        $contentType = $this->verifyIsAnAcceptedImage($file->getPathname());

        // The uploader never chooses the name: a name they control is a path
        // traversal and an overwrite waiting to happen (F04 R20).
        $filename = bin2hex(random_bytes(16)).$this->extensionFor($contentType);

        $this->ensureDirectory();
        $file->move($this->directory, $filename);

        return ['filename' => $filename, 'contentType' => $contentType];
    }

    public function pathFor(string $filename): string
    {
        // Defensive: the stored name is always generated, but a value read
        // back from the database should still never be able to climb out of
        // the upload directory.
        return $this->directory.'/'.basename($filename);
    }

    public function exists(?string $filename): bool
    {
        return null !== $filename && is_file($this->pathFor($filename));
    }

    /**
     * F35 R14. Where a stored picture is served from.
     *
     * Built here rather than at each caller because two of them need it —
     * the player's payload and the admin's — and a path that is written
     * twice is a path that eventually differs between the screen that shows
     * the picture and the one that uploaded it.
     *
     * The timestamp is the game's own: it moves whenever the picture is
     * replaced, so a browser is never left holding the old one, and it does
     * not move while the picture is unchanged, so it is not fetched twice.
     */
    public function urlFor(string $linkKey, \DateTimeImmutable $updatedAt): string
    {
        return '/api/branding/background/'.$linkKey.'?v='.$updatedAt->getTimestamp();
    }

    /**
     * What to serve the stored file as.
     *
     * Read back off the extension, which is safe here in a way it would
     * never be on an upload: this name was generated by {@see store} from a
     * type that had already been verified by reading the file. It is our own
     * record being read back, not the uploader's claim being trusted — which
     * is why there is no third column holding the same fact twice.
     */
    public function contentTypeFor(string $filename): string
    {
        return match (strtolower(pathinfo($filename, \PATHINFO_EXTENSION))) {
            'png' => 'image/png',
            'jpg' => 'image/jpeg',
            'webp' => 'image/webp',
            default => 'application/octet-stream',
        };
    }

    /** F35 R11, R12. */
    public function delete(?string $filename): void
    {
        if (null === $filename) {
            return;
        }

        $path = $this->pathFor($filename);

        if (is_file($path)) {
            @unlink($path);
        }
    }

    /**
     * F35 R7, R9, R10, in that order, because the first question is whether
     * this is an image at all and the rest only make sense once it is.
     *
     * `getimagesize` parses the file header, so a text file renamed to .png
     * and declared as image/png fails here. It is part of PHP's core rather
     * than GD, so this works wherever the app runs — and it is also where
     * the dimensions come from, which is why they are checked here and not
     * in a second pass over the file.
     *
     * @throws UploadRejected
     */
    private function verifyIsAnAcceptedImage(string $path): string
    {
        $info = @getimagesize($path);

        if (false === $info) {
            throw new UploadRejected('background.not_an_image', [], 'That file is not an image.');
        }

        $type = $info[2] ?? null;

        if (!\is_int($type) || !isset(self::ACCEPTED[$type])) {
            throw new UploadRejected(
                'background.wrong_type',
                [],
                'The background is not an accepted image type.',
            );
        }

        $width = (int) ($info[0] ?? 0);
        $height = (int) ($info[1] ?? 0);

        if (max($width, $height) < self::MIN_LONGEST_SIDE) {
            throw new UploadRejected(
                'background.too_small',
                ['%min%' => self::MIN_LONGEST_SIDE, '%width%' => $width, '%height%' => $height],
                'The background is too small.',
            );
        }

        if (max($width, $height) > self::MAX_SIDE) {
            throw new UploadRejected(
                'background.too_big',
                ['%max%' => self::MAX_SIDE, '%width%' => $width, '%height%' => $height],
                'The background is too big.',
            );
        }

        return self::ACCEPTED[$type];
    }

    /** One decimal, so a 5.4MB file does not report itself as 5MB and a limit of 5MB. */
    private function megabytes(int $bytes): string
    {
        return number_format($bytes / 1024 / 1024, 1);
    }

    private function extensionFor(string $contentType): string
    {
        return match ($contentType) {
            'image/png' => '.png',
            'image/jpeg' => '.jpg',
            'image/webp' => '.webp',
            default => '',
        };
    }

    private function ensureDirectory(): void
    {
        if (!is_dir($this->directory) && !mkdir($this->directory, 0o775, true) && !is_dir($this->directory)) {
            throw new \RuntimeException(sprintf('Could not create %s.', $this->directory));
        }
    }
}
